#!/usr/bin/env bash
# 재현 가능한 전량 검증의 진입점.
#
# 선언된 집합과 그 갈래와 단계 본문은 `scripts/vrun.py` 와 그것이 들이는 단계 모듈이 든다.
# 이 자리는 그 모듈을 부르는 것만 들며, 단계의 목록과 갈래를 여기에 다시 적지 않는다. 적으면
# 그 둘이 갈리고 어느 쪽이 선언인지가 서지 않기 때문이다.
#
# 자기 출력의 정규화 해시도 그 모듈이 든다. 받은 판은 이 자리에서 자기를 자식으로 다시 불러
# 그 출력을 모아 해시를 냈고, 그 꼴이 전량을 두 번 띄우면서 끼인 파이썬에 정규화를 두었다.
# 모으는 자리와 내는 자리가 한 과정 안에 서면 그 다시 부르기가 사라진다.
#
# 아크를 닫는 커밋에서는 아크 이름을 첫 인자로 준다. 그 인자가 원장 검증기의 `--arc-close` 로
# 그대로 넘어가고, 주지 않으면 그 인자 없이 불린다.
#
# 실행: bash scripts/verify.sh [<아크>]
set -uo pipefail

export PATH=/root/.elan/bin:$PATH
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

exec python3 scripts/vrun.py "$@"
