#!/usr/bin/env python3
"""`step6-ledger` 의 본문. 원장 검증기를 부른다.

그 검증기는 자기 진입점을 가진 스크립트이고 음성 대조가 그것을 사본의 뿌리를 주어 하위
프로세스로 부르므로, 이 자리가 그것을 들이지 않고 하위 프로세스로 부르는 꼴을 그대로 둔다.
단계가 부르는 모듈을 직접 들이는 가름은 `vstep_*` 에만 걸린다.

첫 인자를 아크 이름으로 읽어 `--arc-close` 로 넘기는 자리는 오케스트레이터가 들고 이 자리는
그 값을 받아 꼬리에 붙인다. 주지 않으면 그 인자 없이 부르므로 호출이 글자대로 그대로다.
"""


def run(ctx) -> None:
    # 받은 판의 셸은 두 흐름을 터미널에 함께 흘렸다. 섞인 꼴로 받아 그대로 내므로 그 순서가
    # 보존되고 자기 출력의 정규화 해시가 그 줄을 입력으로 받는다.
    p = ctx.run(["python3", "scripts/check_wiki.py", *ctx.arc_close], merge=True)
    if p.out:
        ctx.write(p.out)
    if p.rc == 0:
        ctx.ok("원장 검증 전량 통과")
    else:
        ctx.bad("원장 검증 실패 — 위 [check:*] 줄이 어느 검사인지 든다 (SPEC.md §2)")
